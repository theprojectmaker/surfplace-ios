// Turns the SurfPlace web app into src/page.js: ONE self-contained HTML string the
// native WebView loads (all CSS, JS and the world coastline inlined, nothing to 404).
// If the web app lives next door (../surfplace) it is copied into ./web first, so
// ./web is always the exact source of the committed page.
// Run: node tools/build-native.mjs   (commit web/ and the generated src/page.js)
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const web = path.join(root, 'web');
const source = path.join(root, '..', 'surfplace');
const FILES = ['index.html', 'style.css', 'beaches-us.js', 'data.js', 'knowledge.js', 'tide-stations.js', 'live.js',
  'forecast.js', 'map.js', 'scene.js', 'app.js', 'land-10m.json', 'vendor/leaflet.js', 'vendor/leaflet.css'];

if (fs.existsSync(path.join(source, 'index.html'))) {
  for (const f of FILES) {
    fs.mkdirSync(path.dirname(path.join(web, f)), { recursive: true });
    fs.copyFileSync(path.join(source, f), path.join(web, f));
  }
  console.log('Copied the web app from ../surfplace into web/');
}

const read = (f) => fs.readFileSync(path.join(web, f), 'utf8');
// a literal </script> inside inlined code would end the tag early
const safe = (js) => js.replace(/<\/script/gi, '<\\/script');
let html = read('index.html');
let count = 0;

html = html.replace(/<link rel="stylesheet" href="([^":]+)">/g, (m, href) => {
  count++;
  return '<style>\n' + read(href) + '\n</style>';
});
html = html.replace(/<script src="([^":]+)"><\/script>/g, (m, src) => {
  count++;
  // the map reads the coastline from window.LAND_TOPO instead of fetching a file
  const land = src === 'map.js' ? '<script>window.LAND_TOPO=' + safe(JSON.stringify(JSON.parse(read('land-10m.json')))) + ';</script>\n' : '';
  return land + '<script>\n' + safe(read(src)) + '\n</script>';
});

if (count !== 12) throw new Error('build-native: expected 12 local files to inline, found ' + count);
if (/(src|href)="(?!https?:|data:|#)[^"]+\.(js|css)"/.test(html)) throw new Error('build-native: a local file was not inlined');
if (!html.includes('window.LAND_TOPO=') || !html.includes('window.ReactNativeWebView')) throw new Error('build-native: page is missing the coastline or the native bridge');

fs.mkdirSync(path.join(root, 'src'), { recursive: true });
fs.writeFileSync(path.join(root, 'src', 'page.js'),
  '// Generated by tools/build-native.mjs from web/. Do not edit by hand.\nmodule.exports = ' + JSON.stringify(html) + ';\n');
console.log('Wrote src/page.js (' + (html.length / 1048576).toFixed(2) + ' MB) from ' + count + ' files');
