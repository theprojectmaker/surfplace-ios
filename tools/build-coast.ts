// Packs the world coastline into src/data/coast.ts: every ring unwrapped across the date line
// (so it is one continuous shape), simplified, and stored as a single base64 string of float32s.
// Run: npx tsx tools/build-coast.ts   (reads ../surfplace/land-10m.json, Natural Earth, public domain)
import fs from 'fs';
import path from 'path';
import { ringsFromTopo, Topo } from '../src/map/coast';

const TOL = Number(process.env.TOL || 0.012); // degrees, about 1.3 km: the source data is only accurate to about a kilometre
const root = path.join(__dirname, '..');
const topo = JSON.parse(fs.readFileSync(path.join(root, '..', 'surfplace', 'land-10m.json'), 'utf8')) as Topo;

// Douglas-Peucker on a polyline p[from..to] (indices into points), iterative
function simplifyLine(p: Float64Array, keep: Uint8Array, from: number, to: number) {
  const stack: [number, number][] = [[from, to]];
  while (stack.length) {
    const [a, b] = stack.pop() as [number, number];
    if (b <= a + 1) continue;
    const ax = p[2 * a], ay = p[2 * a + 1], bx = p[2 * b], by = p[2 * b + 1];
    const dx = bx - ax, dy = by - ay, len2 = dx * dx + dy * dy;
    let worst = -1, wd = TOL * TOL;
    for (let i = a + 1; i < b; i++) {
      const px = p[2 * i] - ax, py = p[2 * i + 1] - ay;
      let d2: number;
      if (len2 === 0) d2 = px * px + py * py;
      else {
        const t = Math.max(0, Math.min(1, (px * dx + py * dy) / len2));
        const ex = px - t * dx, ey = py - t * dy;
        d2 = ex * ex + ey * ey;
      }
      if (d2 > wd) { wd = d2; worst = i; }
    }
    if (worst >= 0) { keep[worst] = 1; stack.push([a, worst], [worst, b]); }
  }
}

function simplifyRing(r: Float64Array): number[] {
  const n = r.length / 2;
  // drop the closing duplicate point if present
  const last = n - 1;
  const closed = r[0] === r[2 * last] && r[1] === r[2 * last + 1];
  const m = closed ? n - 1 : n;
  if (m < 4) return [];
  const keep = new Uint8Array(m);
  keep[0] = 1;
  // split the ring at the point farthest from the start, then simplify both halves
  let far = 1, fd = -1;
  for (let i = 1; i < m; i++) {
    const d = (r[2 * i] - r[0]) ** 2 + (r[2 * i + 1] - r[1]) ** 2;
    if (d > fd) { fd = d; far = i; }
  }
  keep[far] = 1;
  // work on the points as an open polyline ending back at the start
  const pts = new Float64Array((m + 1) * 2);
  pts.set(r.subarray(0, m * 2));
  pts[2 * m] = r[0]; pts[2 * m + 1] = r[1];
  const keep2 = new Uint8Array(m + 1);
  keep2[0] = 1; keep2[m] = 1; keep2[far] = 1;
  simplifyLine(pts, keep2, 0, far);
  simplifyLine(pts, keep2, far, m);
  const out: number[] = [];
  for (let i = 0; i < m; i++) if (keep2[i]) out.push(pts[2 * i], pts[2 * i + 1]);
  if (out.length < 8) return []; // fewer than 4 points: a speck smaller than the tolerance
  return out;
}

const rings = ringsFromTopo(topo);
let before = 0, after = 0;
const kept: number[][] = [];
for (const r of rings) {
  before += r.length / 2;
  const s = simplifyRing(r);
  if (s.length) { kept.push(s); after += s.length / 2; }
}

const total = 1 + kept.reduce((a, s) => a + 1 + s.length, 0);
const f = new Float32Array(total);
let k = 0;
f[k++] = kept.length;
for (const s of kept) { f[k++] = s.length / 2; for (const v of s) f[k++] = v; }
const b64 = Buffer.from(f.buffer).toString('base64');

fs.writeFileSync(path.join(root, 'src', 'data', 'coast.ts'),
  '// Generated by tools/build-coast.ts from Natural Earth land (public domain). Do not edit by hand.\n' +
  '// Packed rings: see decodeRings in src/map/coast.ts.\n' +
  'export const COAST = \'' + b64 + '\';\n');
console.log('rings ' + rings.length + ' -> ' + kept.length + ', points ' + before + ' -> ' + after +
  ', file ' + (b64.length / 1024).toFixed(0) + ' KB (tolerance ' + TOL + ' deg)');
